"""Database boundary for NowUp: SQLite fallback and parameterized PostgreSQL.

Existing modules keep the SQLite row/cursor interface. No global monkey patches.
PostgreSQL statement errors roll back to a savepoint, preserving the caller's
transaction, so existing IntegrityError handlers retain atomic behavior.
"""
import os
import re
import sqlite3
from functools import lru_cache
from decimal import Decimal
from collections.abc import Mapping

# SQL lexer keeps literals/comments intact: never substitute inside user values.
TOKEN = re.compile(r"('(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|--[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_][A-Za-z_0-9]*\b|\?|%|;|.)", re.S)

def postgres_enabled():
    value = os.getenv('DATABASE_URL', '').strip()
    if os.getenv('NOWUP_DB_BACKEND')=='postgresql' and not value:
        raise RuntimeError('DATABASE_URL é obrigatória quando NOWUP_DB_BACKEND=postgresql.')
    if value and not value.startswith(('postgres://', 'postgresql://')):
        raise RuntimeError('DATABASE_URL deve conter uma conexão PostgreSQL válida.')
    return bool(value)

def connect(path=None, **kwargs):
    if postgres_enabled():
        import psycopg
        return Connection(psycopg.connect(os.environ['DATABASE_URL'], connect_timeout=10,
                          options='-c timezone=UTC -c statement_timeout=30000 -c lock_timeout=10000'))
    c = sqlite3.connect(path, **kwargs)
    c.row_factory = sqlite3.Row
    c.execute('PRAGMA foreign_keys=ON')
    return c

class Row(Mapping):
    def __init__(self, names, values):
        self._values = tuple((int(v) if v == v.to_integral_value() else float(v)) if isinstance(v, Decimal) else v for v in values)
        self._names = tuple(names)
        self._map = dict(zip(names, self._values))
    def __getitem__(self, key):
        return self._values[key] if isinstance(key, (int, slice)) else self._map[key]
    def __iter__(self): return iter(self._map)
    def __len__(self): return len(self._map)
    def keys(self): return self._map.keys()

class Cursor:
    def __init__(self, cursor=None, rows=None, lastrowid=None):
        self._cursor = cursor
        self._rows = iter(rows) if rows is not None else None
        self.lastrowid = lastrowid
        self.rowcount = cursor.rowcount if cursor else len(rows or [])
        self.description = cursor.description if cursor else None
    def fetchone(self):
        if self._rows is not None: return next(self._rows, None)
        if not self._cursor.description: return None
        values = self._cursor.fetchone()
        return None if values is None else Row([c.name for c in self._cursor.description], values)
    def fetchall(self): return list(self)
    def __iter__(self): return self
    def __next__(self):
        row = self.fetchone()
        if row is None: raise StopIteration
        return row
    def close(self):
        if self._cursor: self._cursor.close()

@lru_cache(maxsize=2048)
def convert(statement):
    """Translate only fixed application SQL; values always use driver parameters."""
    statement = statement.strip().rstrip(';')
    if re.match(r'^(CREATE|ALTER)\b', statement, re.I):
        # DDL in this project has no quoted identifiers containing these words.
        # sqlglot parses DDL, including constraints and double quoted defaults.
        import sqlglot
        statement = re.sub(r'\bINTEGER\s+PRIMARY\s+KEY(?:\s+AUTOINCREMENT)?',
                           'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', statement, flags=re.I)
        statement = sqlglot.transpile(statement, read='sqlite', write='postgres', unsupported_level=sqlglot.ErrorLevel.RAISE)[0]
        statement = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', statement, flags=re.I)
        return statement
    ignore = bool(re.match(r'^INSERT\s+OR\s+IGNORE\b', statement, re.I))
    replace = bool(re.match(r'^INSERT\s+OR\s+REPLACE\s+INTO\s+push_subscriptions\b', statement, re.I))
    statement = re.sub(r'^INSERT\s+OR\s+(IGNORE|REPLACE)\b', 'INSERT', statement, flags=re.I)
    tokens = TOKEN.findall(statement)
    out = []
    for token in tokens:
        low = token.lower()
        if token == '?': out.append('%s')
        elif token == '%': out.append('%%')
        elif token.startswith(("'", '"', '--', '/*')): out.append(token.replace('%','%%'))
        elif low == 'like': out.append('ILIKE')
        elif low == 'julianday': out.append('nowup_julianday')
        elif low == 'datetime': out.append('nowup_datetime')
        elif low == 'date': out.append('nowup_date')
        elif low == 'instr': out.append('strpos')
        else: out.append(token)
    statement = ''.join(out)
    if ignore: statement += ' ON CONFLICT DO NOTHING'
    if replace:
        statement += ' ON CONFLICT (endpoint) DO UPDATE SET user_id=EXCLUDED.user_id, session_hash=EXCLUDED.session_hash, subscription=EXCLUDED.subscription'
    return statement

class Connection:
    def __init__(self, connection):
        self.raw = connection
        self._ids = {}
        self.row_factory = None
    def execute(self, statement, parameters=()):
        import psycopg
        pragma = re.fullmatch(r'\s*PRAGMA\s+table_info\(([^)]+)\)\s*;?\s*', statement, re.I)
        if pragma:
            table = pragma[1].strip('"\' ')
            cur = self.raw.execute("SELECT ordinal_position-1 AS cid,column_name AS name,data_type AS type,CASE WHEN is_nullable='NO' THEN 1 ELSE 0 END AS notnull,column_default AS dflt_value,0 AS pk FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s ORDER BY ordinal_position",(table,))
            return Cursor(cur)
        if re.match(r'\s*PRAGMA\s+foreign_keys', statement, re.I): return Cursor(rows=[])
        if re.fullmatch(r'\s*BEGIN(?:\s+IMMEDIATE)?\s*;?\s*', statement, re.I):
            return Cursor(self.raw.execute('SELECT pg_advisory_xact_lock(223002)'))
        query = convert(statement)
        match = re.match(r'^INSERT\s+INTO\s+([a-z_0-9]+)', query, re.I)
        returning = False
        if match and not re.search(r'\bRETURNING\b',query,re.I):
            table = match[1].lower()
            if table not in self._ids:
                self._ids[table] = bool(self.raw.execute("SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s AND column_name='id'",(table,)).fetchone())
            if self._ids[table]: query += ' RETURNING id'; returning = True
        # Savepoint is released only after a successful statement. Commit remains
        # exclusively the caller's decision; caught uniqueness errors do not
        # invalidate all preceding work in the transaction.
        self.raw.execute('SAVEPOINT nowup_statement')
        try:
            cur = self.raw.execute(query, None if re.match(r'^(CREATE|ALTER)\b', query, re.I) else parameters)
            result = Cursor(cur)
            if returning:
                row = cur.fetchone()
                result.lastrowid = row[0] if row else None
            self.raw.execute('RELEASE SAVEPOINT nowup_statement')
            if re.match(r'^(CREATE|ALTER)\b',query,re.I): self._ids.clear()
            return result
        except psycopg.Error as exc:
            self.raw.execute('ROLLBACK TO SAVEPOINT nowup_statement')
            self.raw.execute('RELEASE SAVEPOINT nowup_statement')
            if isinstance(exc, psycopg.IntegrityError):
                raise sqlite3.IntegrityError('Restrição de integridade do banco.') from exc
            raise
    def executescript(self, script):
        # Split statements without splitting quoted text or SQL comments.
        part=[]
        for token in TOKEN.findall(script):
            if token == ';':
                if ''.join(part).strip(): self.execute(''.join(part))
                part=[]
            else: part.append(token)
        if ''.join(part).strip(): self.execute(''.join(part))
        return self
    def executemany(self, query, rows):
        result=Cursor(rows=[])
        for row in rows: result=self.execute(query,row)
        return result
    def commit(self): self.raw.commit()
    def rollback(self): self.raw.rollback()
    def close(self): self.raw.close()
    def __enter__(self): return self
    def __exit__(self, typ, value, tb):
        self.rollback() if typ else self.commit()

# Temporal compatibility for existing ISO text columns: normalize UTC and
# invalid/empty dates to NULL, matching SQLite's report/session behavior.
TEMPORAL_SQL = r"""
CREATE OR REPLACE FUNCTION nu177_normalize(value text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
 SELECT trim(replace(lower(regexp_replace(normalize(coalesce(value,''), NFKD), U&'[\0300-\036f]', '', 'g')), 'ß', 'ss'))
$$;
CREATE OR REPLACE FUNCTION nowup_datetime(value text) RETURNS timestamptz LANGUAGE plpgsql STABLE AS $$
BEGIN
 IF value IS NULL OR value='' THEN RETURN NULL; END IF;
 IF value='now' THEN RETURN CURRENT_TIMESTAMP; END IF;
 RETURN value::timestamptz;
EXCEPTION WHEN invalid_datetime_format OR datetime_field_overflow THEN RETURN NULL;
END $$;
CREATE OR REPLACE FUNCTION nowup_julianday(value text) RETURNS double precision LANGUAGE sql STABLE AS $$
 SELECT EXTRACT(EPOCH FROM nowup_datetime(value))::double precision/86400.0+2440587.5
$$;
CREATE OR REPLACE FUNCTION nowup_julianday(value text, modifier text) RETURNS double precision LANGUAGE sql STABLE AS $$
 SELECT EXTRACT(EPOCH FROM (nowup_datetime(value)+modifier::interval))::double precision/86400.0+2440587.5
$$;
CREATE OR REPLACE FUNCTION nowup_date(value text) RETURNS text LANGUAGE sql STABLE AS $$
 SELECT to_char(nowup_datetime(value) AT TIME ZONE 'UTC','YYYY-MM-DD')
$$;
CREATE OR REPLACE FUNCTION nowup_date(value text, modifier text) RETURNS text LANGUAGE sql STABLE AS $$
 SELECT to_char((nowup_datetime(value)+modifier::interval) AT TIME ZONE 'UTC','YYYY-MM-DD')
$$;
CREATE OR REPLACE FUNCTION nowup_date(value text, first_modifier text, second_modifier text) RETURNS text LANGUAGE sql STABLE AS $$
 SELECT to_char((nowup_datetime(value)+first_modifier::interval+second_modifier::interval) AT TIME ZONE 'UTC','YYYY-MM-DD')
$$;

"""

def initialize_postgres():
    if not postgres_enabled(): return
    c=connect()
    try:
        # Shared startup lock prevents concurrent schema creation by workers.
        c.raw.execute('SELECT pg_advisory_xact_lock(223001)')
        c.raw.execute(TEMPORAL_SQL)
        c.commit()
    finally: c.close()
